"""
Builds lib/src/items.ts and public/items/<id>.webp from item list pages of
https://metaforge.app/rob-run/database saved with "Save page as > Web page, complete".

Usage: python scripts/import-items.py <folder with the saved pages>
Every saved page is read, items are merged by id (the last part of their URL).
"""
import html
import json
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT_TS = ROOT / "lib" / "src" / "items.ts"
OUT_IMAGES = ROOT / "public" / "items"

# Pages saved by different browsers order the attributes differently.
ITEM_RE = re.compile(r'<li[^>]*>\s*<a[^>]*href="https://metaforge\.app/rob-run/database/([a-z0-9-]+)"[^>]*>(.*?)</a>\s*</li>', re.S)


def text(fragment):
    return html.unescape(re.sub(r"<[^>]+>", "", fragment)).strip()


def spans(fragment):
    # Texts of the innermost spans, in order.
    return [text(value) for value in re.findall(r"<span[^>]*>([^<]*)</span>", fragment) if text(value)]


def parse_item(item_id, body):
    image = re.search(r'<img src="([^"]+)"', body)
    rarity = re.search(r'<span[^>]*style="color:\s*([^";]+);?"[^>]*>([^<]+)</span>', body)
    values = spans(body)
    price = next((value for value in reversed(values) if re.fullmatch(r"\$[\d,]+", value)), None)

    name = values[0]
    rest = [value for value in values[1:] if value != price and (not rarity or value != rarity.group(2))]
    subtitle = rest[0] if rest else ""
    description = rest[1] if len(rest) > 1 else ""

    # "Level 1 · Full" or "SMG · Mk1": the part after the dot is the detail.
    head, _, detail = (part.strip() for part in subtitle.partition("·"))
    level = re.fullmatch(r"Level (\d+)", head)

    return {
        "id": item_id,
        "name": name,
        "rarity": rarity.group(2) if rarity else None,
        "category": None if level else head or None,
        "level": int(level.group(1)) if level else None,
        "detail": detail or None,
        "price": int(price[1:].replace(",", "")) if price else None,
        "description": description or None,
        "imageFile": Path(image.group(1)).name if image else None,
    }


def find_image(folder, file_name):
    matches = list(folder.glob(f"**/{file_name}"))

    return matches[0] if matches else None


def main():
    folder = Path(sys.argv[1])
    items = {}
    pages = 0

    for page in sorted(folder.iterdir()):
        if not page.is_file() or page.suffix in {".css", ".js", ".webp", ".png", ".jpg"}:
            continue

        source = page.read_text(encoding="utf-8", errors="replace")

        if "rob-run/database" not in source:
            continue

        pages += 1
        for item_id, body in ITEM_RE.findall(source):
            items[item_id] = parse_item(item_id, body)

    OUT_IMAGES.mkdir(parents=True, exist_ok=True)
    missing = []

    for item in items.values():
        image = find_image(folder, item.pop("imageFile")) if item.get("imageFile") else None

        if image:
            shutil.copyfile(image, OUT_IMAGES / f"{item['id']}{image.suffix}")
            item["image"] = f"/items/{item['id']}{image.suffix}"
        else:
            item["image"] = None
            missing.append(item["id"])

    ordered = sorted(items.values(), key=lambda item: (item["name"].lower(), item["id"]))
    entries = ",\n".join(f"    {json.dumps(item, ensure_ascii=False)}" for item in ordered)

    OUT_TS.write_text(f'''import "server-only"
import type {{ Item }} from "@/types"

// ROB RUN items, generated by scripts/import-items.py from saved pages of
// https://metaforge.app/rob-run/database. Do not edit by hand, run the script again.
// The id (last part of the item URL) is saved in `ClanInventoryItem.itemId`.
// Server only: send items to the browser as ItemDto, never the whole list.
export const items = [
{entries},
] as const satisfies readonly Item[]

export type ItemId = (typeof items)[number]["id"]

export const itemIds = items.map(({{ id }}) => id) as [ItemId, ...ItemId[]]

/** An item by its id, undefined if it is unknown. */
export function getItem(itemId: string): Item | undefined {{
    return items.find(({{ id }}) => id === itemId)
}}

/** Name of an item, the id itself if it is unknown. */
export function getItemName(itemId: string): string {{
    return getItem(itemId)?.name ?? itemId
}}
''', encoding="utf-8")

    print(f"{pages} pages, {len(items)} items, {len(missing)} without image")
    if missing:
        print("without image:", ", ".join(missing))


main()
